            <h2>What is Mutual Aid?</h2>
            <p>
                In simple terms mutual aid is when you let your neighbour have some milk because you know they will give you some eggs next time you run out. It is the acknowledgment that we don't need a reward monetary or otherwise to help each other. It is a non-hierarchical
                form of organising to ensure we have our needs met. It is not charity. We believe that those we assist provide or will provide equal or greater value to our community.<br>
                Mutual Aid is a philosophy of sharing resources and building support that doesn't
                involve an external body, like a government or state, and so hopefully avoids many of the problems that come with relying only on the state to look after you.
