                <b>Why direct Giving?<br></b>
                In a capitalist society most problems can be solved with three things: Money, Information and Emotional Support. 
                Typically people know what they need better than some third party sat in an office somewhere. Giving people financial aid directly is the most efficient way to help a group, 
                our overhead costs are miniscule allowing the vast majority of funding to go to those who need it.<br>
            <p>
                <b>Can you help me get HRT?</b><br>
                We don't advertise grey or black market sources here. Check popular web forums or go to a social event there will be a lot of people DIYing who can advise you on sources.
            </p>
            <p>
                <b>I am in urgent need but your team won't approve a grant</b><br>
                All grants are limited by time and amount. This is to ensure that the grants are spread evenly between those in need. We are a group of volunteers working entirely from donations,
                occasionally things can get lost in our system and require chasing up. However, if you attempt to bypass our restrictions or intimidate our team you will be blocked from all future grants.
            </p>
            </p><p>    
                <b>Who runs TMAM?<br></b>
                Our current directors are viewable on the Companies House website. Our teams are staffed by volunteers whom are trans+ people who live in Manchester.
                Since we incorporated we can no longer be a purely directly democratic organisation, 
                to ensure we are meeting the needs of the whole trans community in Manchester we aim to have a director from each section of it who can cover blind spots in each of our knowledge.<br>
            </p><p>    
                <b>How much can I ask for?<br></b>
                We regularly meet to adjust how much and how often people can request financial assistance. These adjustments are required to avoid the fund running dry. 
                We discourage relying on us for repeat payments as we may have to turn you away. Our goal is to help as many people as possible.<br>
            </p><p>    
                <b>How do you decide who gets grants?<br></b>
                You must be a trans person living in Manchester. We need to know the amount you need and what for as this helps us know what we need to work on. 
                There are no restriction on what you can use the funding for so there is no need to lie to get funding. To insure our funding goes where it is needed we will ask a few verification questions.<br>
            </p><p>
                <b>How do you keep my information safe?</b><br>
                Once we finish dealing with your request all your correspondence and data is removed from our active systems and moved to an archive with limited access.
                We keep this information only for the unlikely case that we have a financial audit, your information will then be deleted after two years. We keep secure unreversable hashes of certain information to allow us to check for repeat requests etc.
            </p>
            </p><p>    
                <b>Mutual aid is an anarchist principle, how radical are you really?</b><br>
                The structure of a community interest company is not anarchist but it does allow us to get things done. Our grants fund operates more akin to a charity than a true mutual aid fund. 
                These were decisions with practicality in mind. Some weaknesses of anarchist organisation are that no one agrees on the best way to do it and very few people have any practice operating in any of them. 
                They also tend to be short lived and function best with a specific concrete objective. What we do requires continuous presence and easy onboarding of new people.<br>
                We don't have any agreed upon political positions as an organisation, any espoused views ultimately are those of whomever is running our social media or maintaining this site at the time. 
                Disagreements within the organisation have been rare and insignificant, our members have the sorts of views you would expect from people who want to run an organisation named after an anarchist principle.<br>
            </p><p>
                <b>What sort of work could I be doing if I join TMAM?</b><br>
                Anything you have the dedication for and want to do. If you have an idea that helps make trans people in Manchester's lives easier we're more than happy for you to do it through our organisation. We're also always looking for more people to respond to grant requests as it is not the most enjoyable job and has higher turnover.<br>
                
                There are several things we would like to do that get floated at meetings regularly that we don't have the time or experience to organise. Current roles we would like to fill at time of writing: improved GP mapping, strong intergroup networking, skills workshops.<br>
            </p><p>    
                <b>How can you assist refuges?</b><br>
                If you move to Manchester we will help you in our usual ways to the best of our ability, however given the difficulty of such a move and the unfortunate fact that the UK is on a quick downward trend in our legal rights we recommend finding somewhere else to emigrate to.
                Many trans people in the UK have been considering what their exit plans are for a number of years now. There are other organisations that can help you with claiming asylum such as <a href="https://transrescue.org/">Trans Rescue</a> and <a href="https://www.rainbowmigration.org.uk/">Rainbow Migration</a><br>
